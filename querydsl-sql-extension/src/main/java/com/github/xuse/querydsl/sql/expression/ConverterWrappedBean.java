package com.github.xuse.querydsl.sql.expression;

import java.util.HashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;
import java.util.function.Function;

import com.github.xuse.querydsl.annotation.query.PathBinder;
import com.github.xuse.querydsl.config.ConfigurationEx;
import com.github.xuse.querydsl.sql.RelationalPathEx;
import com.github.xuse.querydsl.util.collection.MapCreator;
import com.querydsl.core.types.Path;
import com.querydsl.sql.RelationalPath;

import lombok.extern.slf4j.Slf4j;

/**
 * <h2>English:</h2>
 * A wrapper that adapts a DTO object for use with {@link AdvancedMapper}.
 * <p>
 * When a DTO with {@link PathBinder} annotations is passed to {@code populate()},
 * the framework automatically detects and handles field name remapping and type conversion.
 * All existing AdvancedMapper logic (null strategies, {@code @AutoGenerated},
 * {@code @UnsavedValue}, {@code notInsert}/{@code notUpdate}) works transparently.
 * </p>
 *
 * <h2>Value ordering concepts:</h2>
 * <ul>
 *   <li><b>Original column order (原始列序)</b>: {@code entity.getColumns()} — all columns of the table.</li>
 *   <li><b>Effective column order (有效列序)</b>: A subset of the original column order after
 *       AdvancedMapper filters out primary keys, notInsert/notUpdate columns, and (in selective mode)
 *       null-value columns. This is the column set that actually participates in the SQL statement.</li>
 *   <li><b>SQL expanded column order (SQL展开列序)</b>: After serialization, typically identical to
 *       effective column order for INSERT statements (no expansion occurs in INSERT context).</li>
 * </ul>
 * <p>
 * {@link #extractValues(RelationalPathEx)} produces values in <b>original column order</b>,
 * consumed by {@link AdvancedMapper#createMap} which then filters to effective columns.
 * <p>
 * {@link #toValueExtractor(RelationalPathEx, List)} produces a {@link ValueExtractor} that
 * outputs values in <b>effective column order</b> (the constantPath from BatchProcessor),
 * used for batch insert where the SQL structure is fixed by the first bean.
 *
 * <h2>Chinese:</h2>
 * 将 DTO 对象适配到 {@link AdvancedMapper} 使用的工具类。
 * <p>
 * 值序说明：
 * <ul>
 *   <li><b>原始列序</b>：entity.getColumns() 全部列。</li>
 *   <li><b>有效列序</b>：AdvancedMapper 过滤掉主键、notInsert/notUpdate、空值列后的子集。
 *       即实际参与 SQL 的列集合。</li>
 *   <li><b>SQL展开列序</b>：序列化后的绑定变量顺序，INSERT 场景下与有效列序一致。</li>
 * </ul>
 * {@link #extractValues} 按原始列序输出，供 AdvancedMapper 逐列判断过滤。
 * {@link #toValueExtractor} 按有效列序输出，供 BatchProcessor 直接绑定参数。
 *
 * <p>Usage:</p>
 * <pre>
 * // Explicit wrapping (optional)
 * factory.insert(fooPath).populate(ConverterWrappedBean.of(fooDTO)).execute();
 *
 * // Or just pass the DTO directly - auto-detected if it has @PathBinder annotations
 * factory.insert(fooPath).populate(fooDTO).execute();
 * </pre>
 *
 * @author Joey
 */
@Slf4j
public class ConverterWrappedBean {

	/**
	 * Sentinel value indicating that the DTO has no mapping for this entity column.
	 * <p>
	 * When {@link #extractValues} encounters a column with no corresponding DTO field
	 * (FieldSlot is null), it places this constant in the result array instead of null.
	 * This allows {@link AdvancedMapper} to distinguish between:
	 * <ul>
	 *   <li>{@code NOT_AVAILABLE} — DTO does not map this column → skip it entirely
	 *       (database DEFAULT takes effect)</li>
	 *   <li>{@code null} — DTO maps this column but the value is null → apply null strategy</li>
	 * </ul>
	 */
	public static final Object NOT_AVAILABLE = new Object() {
		@Override
		public String toString() {
			return "NOT_AVAILABLE";
		}
	};

	/**
	 * Cache: (dtoType, entityType) -> DtoMappingInfo.
	 * The DtoMappingInfo contains the BeanCodec for the DTO and a FieldSlot[] aligned
	 * with the original column order of the entity.
	 */
	private static final Map<ClassPairKey, DtoMappingInfo> MAPPING_CACHE = MapCreator.createConcurrentMap(ConfigurationEx.WRAPPERED_BEAN_CACHE_SIZE);

	private final Object dto;
	private final Class<?> dtoType;

	private ConverterWrappedBean(Object dto) {
		this.dto = dto;
		this.dtoType = dto.getClass();
	}

	/**
	 * Wrap a DTO object explicitly.
	 *
	 * @param dto the DTO object
	 * @return wrapped bean
	 */
	public static ConverterWrappedBean of(Object dto) {
		return new ConverterWrappedBean(dto);
	}

	/**
	 * If the bean is not an instance of the entity type, wrap it for
	 * transparent field name remapping and type conversion.
	 *
	 * @param bean   the bean object
	 * @param entity the target relational path
	 * @return the original bean or a wrapped instance
	 */
	public static Object wrapIfNeeded(Object bean, RelationalPath<?> entity) {
		return entity.getType().isInstance(bean) ? bean : of(bean);
	}

	/**
	 * Get the underlying DTO object.
	 */
	public Object getDto() {
		return dto;
	}

	/**
	 * Create a {@link ValueExtractor} for batch processing.
	 * <p>
	 * The returned extractor produces values in <b>effective column order</b> — i.e. aligned
	 * with the {@code effectivePaths} parameter, which is the column subset that actually
	 * participates in the batch SQL (after AdvancedMapper filtering on the first bean).
	 * <p>
	 * Implementation: maps each effective path back to its position in the original column
	 * order (where DtoMappingInfo.slots is indexed), then extracts only those slots.
	 * The column index mapping is cached per (dtoType, entityType, effectivePaths) combination.
	 *
	 * @param entity         the target table
	 * @param effectivePaths the effective column paths (subset of entity.getColumns(),
	 *                       preserving relative order). This is the constantPath from BatchProcessor.
	 * @return a ValueExtractor that outputs values in effective column order
	 */
	public ValueExtractor toValueExtractor(RelationalPathEx<?> entity, List<Path<?>> effectivePaths) {
		DtoMappingInfo info = getMapping(dtoType, entity);
		int[] columnIndices = info.getOrBuildColumnIndices(entity, effectivePaths);
		return new DtoValueExtractor(dtoType, info, columnIndices);
	}

	// ==================== Original column order extraction ====================

	/**
	 * Extract values from the wrapped DTO in <b>original column order</b>.
	 * <p>
	 * The result array has one element per entity column (entity.getColumns().size()).
	 * Columns not mapped by the DTO will have {@link #NOT_AVAILABLE} values.
	 * This is consumed by {@link AdvancedMapper#createMap}, which iterates all columns
	 * and applies filtering (notInsert, null strategy, @AutoGenerated, etc.).
	 *
	 * @param entity the target table
	 * @return values array aligned with entity.getColumns() order
	 */
	public Object[] extractValues(RelationalPathEx<?> entity) {
		return extractValues(dto, dtoType, entity);
	}

	/**
	 * Static variant of {@link #extractValues(RelationalPathEx)}.
	 */
	public static Object[] extractValues(Object bean, RelationalPathEx<?> entity) {
		return extractValues(bean, bean.getClass(), entity);
	}

	/**
	 * Core extraction in original column order.
	 * Uses cached DtoMappingInfo whose slots[] is indexed by original column position.
	 * <p>
	 * For columns where the DTO has no mapping (slot is null), the result contains
	 * {@link #NOT_AVAILABLE} instead of null, signaling to AdvancedMapper that this
	 * column should be skipped entirely (allowing database DEFAULT to take effect).
	 */
	@SuppressWarnings({ "rawtypes", "unchecked" })
	private static Object[] extractValues(Object bean, Class<?> dtoType, RelationalPathEx<?> entity) {
		DtoMappingInfo info = getMapping(dtoType, entity);
		Object[] dtoValues = info.codec.values(bean);
		FieldSlot[] slots = info.slots;

		Object[] result = new Object[slots.length];
		for (int i = 0; i < slots.length; i++) {
			FieldSlot slot = slots[i];
			if (slot == null) {
				// DTO has no field for this entity column
				result[i] = NOT_AVAILABLE;
			} else {
				result[i] = slot.writeConverter.apply(dtoValues[slot.dtoFieldIndex]);
			}
		}
		return result;
	}

	// ==================== Mapping cache ====================

	/**
	 * Get or build the cached DtoMappingInfo for a (dtoType, entityType) pair.
	 * <p>
	 * The DtoMappingInfo.slots[] is aligned with the <b>original column order</b>
	 * (entity.getColumns()). Each slot maps an entity column to a DTO field index
	 * and its write converter. Null slot means the DTO has no field for that column.
	 */
	@SuppressWarnings("rawtypes")
	private static DtoMappingInfo getMapping(Class<?> dtoType, RelationalPathEx<?> entity) {
		ClassPairKey key = new ClassPairKey(dtoType, entity.getType());
		DtoMappingInfo cached = MAPPING_CACHE.get(key);
		if (cached != null) {
			return cached;
		}
		// Phase 1: Build DTO field metadata: targetName -> (dtoFieldIndex, Property)
		BeanCodec codec = BeanCodecManager.getInstance().getCodec(dtoType);
		Property[] fields = codec.getFields();
		Map<String, int[]> indexMap = new HashMap<>(fields.length);
		for (int i = 0; i < fields.length; i++) {
			Property field = fields[i];
			PathBinder pathBinder = field.getAnnotation(PathBinder.class);
			if (pathBinder != null && !pathBinder.writable()) {
				continue;
			}
			String targetName = (pathBinder == null || pathBinder.value().isEmpty()) ? field.getName() : pathBinder.value();
			indexMap.put(targetName, new int[] { i });
		}

		// Phase 2: Align slots with original column order.
		// Now we know the target column type, so we can resolve write converters
		// with built-in converter fallback.
		List<Path<?>> columns = entity.getColumns();
		FieldSlot[] slots = new FieldSlot[columns.size()];
		for (int c = 0; c < columns.size(); c++) {
			String colName = columns.get(c).getMetadata().getName();
			int[] idx = indexMap.get(colName);
			if (idx == null) {
				continue;
			}
			int fieldIndex = idx[0];
			Property field = fields[fieldIndex];
			PathBinder pathBinder = field.getAnnotation(PathBinder.class);
			Class<?> columnType = columns.get(c).getType();
			Function writeConverter = resolveWriteConverter(dtoType, pathBinder == null ? BuiltinConverters.DEFAULT_PATH_BINDER : pathBinder, field, columnType);
			slots[c] = new FieldSlot(fieldIndex, writeConverter);
		}
		DtoMappingInfo info = new DtoMappingInfo(codec, slots);
		MAPPING_CACHE.put(key, info);
		return info;
	}

	@SuppressWarnings("rawtypes")
	private static Function resolveWriteConverter(Class<?> dtoType, PathBinder pathBinder, Property field, Class<?> columnType) {
		Class<?> refSource = BuiltinConverters.resolveConverterSource(pathBinder, dtoType);
		return BuiltinConverters.resolveConverter(dtoType, field, pathBinder.toDb(),
				pathBinder.toDbRef(), refSource, field.getType(), columnType, pathBinder.skipTypeCheck());
	}

	// ==================== Inner classes ====================

	/**
	 * Cached mapping info for a (dtoType, entityType) pair.
	 * <p>
	 * {@code slots[]} is indexed by original column position (entity.getColumns()).
	 * {@code columnIndicesCache} caches the index mapping from effective column order
	 * to original column order, keyed by the effectivePaths list identity.
	 */
	private static final class DtoMappingInfo {
		final BeanCodec codec;
		/** Indexed by original column position. Null means DTO has no mapping for that column. */
		final FieldSlot[] slots;

		/**
		 * Cache: effectivePaths (by identity) -> int[] mapping from effective position to original position.
		 * In practice, for a given (dtoType, entityType) pair, the effectivePaths is determined by
		 * AdvancedMapper filtering and is stable across batch calls, so this cache has very few entries.
		 */
		private volatile Map<List<Path<?>>, int[]> columnIndicesCache;

		DtoMappingInfo(BeanCodec codec, FieldSlot[] slots) {
			this.codec = codec;
			this.slots = slots;
		}

		/**
		 * Get or build the column index mapping from effective column order to original column order.
		 * Cached by the identity of the effectivePaths list (same list instance = same mapping).
		 */
		int[] getOrBuildColumnIndices(RelationalPathEx<?> entity, List<Path<?>> effectivePaths) {
			Map<List<Path<?>>, int[]> cache = this.columnIndicesCache;
			if (cache != null) {
				int[] cached = cache.get(effectivePaths);
				if (cached != null) {
					return cached;
				}
			}
			// Build: for each path in effectivePaths, find its index in entity.getColumns().
			// effectivePaths is always a subset of entity.getColumns(), so match is guaranteed.
			List<Path<?>> allColumns = entity.getColumns();
			int[] indices = new int[effectivePaths.size()];
			for (int i = 0; i < effectivePaths.size(); i++) {
				String name = effectivePaths.get(i).getMetadata().getName();
				int found = -1;
				for (int c = 0; c < allColumns.size(); c++) {
					if (allColumns.get(c).getMetadata().getName().equals(name)) {
						found = c;
						break;
					}
				}
				assert found >= 0 : "effectivePath '" + name + "' not found in entity columns";
				indices[i] = found;
			}
			// Cache it (small map, typically 1-2 entries per DtoMappingInfo)
			if (cache == null) {
				synchronized (this) {
					if (columnIndicesCache == null) {
						columnIndicesCache = new ConcurrentHashMap<>(2);
					}
					cache = columnIndicesCache;
				}
			}
			cache.put(effectivePaths, indices);
			return indices;
		}
	}

	/**
	 * A {@link ValueExtractor} that extracts DTO values in <b>effective column order</b>.
	 * <p>
	 * Used by BatchProcessor: after the first bean determines the SQL structure (effective columns),
	 * subsequent beans use this extractor to produce values in the same order for parameter binding.
	 * <p>
	 * Internally, it uses {@code columnIndices[]} to map each effective column position back to
	 * the original column position in DtoMappingInfo.slots[], then applies the FieldSlot's
	 * converter to produce the final value.
	 */
	@SuppressWarnings({ "rawtypes", "unchecked" })
	private static final class DtoValueExtractor extends ValueExtractor {
		private final Class<?> dtoType;
		private final DtoMappingInfo info;
		/**
		 * Index mapping: result[i] corresponds to slots[columnIndices[i]] in the original column order.
		 * All values are non-negative (effectivePaths is always a subset of entity columns).
		 */
		private final int[] columnIndices;

		DtoValueExtractor(Class<?> dtoType, DtoMappingInfo info, int[] columnIndices) {
			this.dtoType = dtoType;
			this.info = info;
			this.columnIndices = columnIndices;
		}

		@Override
		public Class<?> getType() {
			return dtoType;
		}

		@Override
		public Object[] values(Object bean) {
			Object actual = (bean instanceof ConverterWrappedBean) ? ((ConverterWrappedBean) bean).getDto() : bean;
			Object[] dtoValues = info.codec.values(actual);
			FieldSlot[] slots = info.slots;
			Object[] result = new Object[columnIndices.length];
			for (int i = 0; i < columnIndices.length; i++) {
				FieldSlot slot = slots[columnIndices[i]];
				if (slot != null) {
					result[i] = slot.writeConverter.apply(dtoValues[slot.dtoFieldIndex]);
				}
			}
			return result;
		}

		@Override
		public boolean isInstance(Object bean) {
			Object actual = (bean instanceof ConverterWrappedBean) ? ((ConverterWrappedBean) bean).getDto() : bean;
			return dtoType.isInstance(actual);
		}
	}

	/**
	 * Mapping for a single entity column to a DTO field.
	 * Stored in DtoMappingInfo.slots[] at the original column position.
	 */
	private static final class FieldSlot {
		/** Index into the DTO's BeanCodec values array. */
		final int dtoFieldIndex;
		/** Write converter (Function.identity() if no conversion needed). Never null. */
		@SuppressWarnings("rawtypes")
		final Function writeConverter;

		@SuppressWarnings("rawtypes")
		FieldSlot(int dtoFieldIndex, Function writeConverter) {
			this.dtoFieldIndex = dtoFieldIndex;
			this.writeConverter = writeConverter;
		}
	}
}
