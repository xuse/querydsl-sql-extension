	/**
	 * Set the data for bulk insertion
	 * <p>
	 * 设置要批量插入的数据
	 *
	 * @implSpec 使用带NULLBinding的方式设置变量，批量装配时，无论是否为null值，都会在SQL中显示声明，因此数据库的默认值将无效
	 * @param beans data to insert
	 * @return this SQLInsertClauseAlter
	 */
	public SQLInsertClauseAlter populateBatch(Collection<?> beans) {
		//退化：走旧Batch路径
		if (getEffectiveBatchNullStrategy() == null) {
			return populateBatchViaAddBatch(beans);
		}
		int type = Mappers.TYPE_BEAN;
		if(writeNulls==null || writeNulls) {
			type = type | Mappers.NULLS_BIND;
		}
		populateBatch0(wrapCollectionIfNeeded(beans), Mappers.get(SCENARIO_INSERT, type));
		return this;
	}

	/**
	 * Fallback path: use the traditional addBatch() approach for each bean.
	 * Each bean is processed through the full Mapper pipeline individually,
	 * so null values on NOT NULL columns are simply omitted from the SQL,
	 * letting the database DEFAULT take effect naturally.
	 * <p>
	 * 安全路径：使用传统的addBatch()方式逐条处理。每条记录独立通过Mapper处理，
	 * null值的NOT NULL字段不会出现在SQL中，数据库DEFAULT自然生效。
	 */
	@SuppressWarnings({ "rawtypes", "unchecked" })
	private SQLInsertClauseAlter populateBatchViaAddBatch(Collection<?> beans) {
		if (beans.isEmpty()) {
			return this;
		}
		// Disable normalization so each bean keeps its own column set.
		// Different beans may produce different SQL statements (grouped and executed separately).
		this.normalizeBatchValues = false;
		Mapper mapper = Mappers.get(SCENARIO_INSERT, Mappers.TYPE_BEAN);
		for (Object bean : beans) {
			Object target = wrapIfNeeded(bean);
			Map<Path<?>, Object> values = mapper.createMap(entity, target);
			for (Map.Entry<Path<?>, Object> entry : values.entrySet()) {
				set((Path) entry.getKey(), entry.getValue());
			}
			addBatch();
		}
		return this;
	}

	/**
	 * Set the data for bulk insertion
	 * <p>
	 * 设置要批量插入的数据
	 *
	 * @param beans  data to insert
	 * @param mapper the mapper object.
	 * @return this SQLInsertClauseAlter
	 * @see AdvancedMapper
	 * @param <T> The type of target object.
	 */
	public <T> SQLInsertClauseAlter populateBatch(Collection<T> beans, Mapper<?> mapper) {
		if (mapper == null) {
			return populateBatch(beans);
		}
		populateBatch0(beans, mapper);
		return this;
	}

	/**
	 * Set the data for bulk insertion (Tuple objects)
	 * <p>
	 * 设置要批量插入的动态数据（用Tuple类型表示）
	 * 
	 * @param beans 数据
	 * @return this
	 */
	public SQLInsertClauseAlter populateTuples(Collection<Tuple> beans) {
		populateBatch0(beans, Mappers.get(SCENARIO_INSERT,Mappers.NULLS_BIND | Mappers.TYPE_TUPLE));
		return this;
	}

	private void populateBatch0(Collection<?> beans, @SuppressWarnings("rawtypes") Mapper mapper) {
		if (beans.isEmpty()) {
			return;
		}
		Collection<Object> batch;
		if ((batch = populatedBatch).isEmpty()) {
			batch = populatedBatch = new ArrayList<>();
		}
		batch.addAll(beans);
		this.batchMapper = mapper;
	}

	/**
	 * {@inheritDoc}
	 */
	@SuppressWarnings("unchecked")
	public SQLInsertClauseAlter populate(Object bean) {
		int type = Mappers.TYPE_BEAN;
		if (writeNulls!=null && writeNulls) {
			type = type | Mappers.NULLS_BIND;
		}
		Object target = wrapIfNeeded(bean);
		populate(target, Mappers.get(SCENARIO_INSERT, type));
		// Mapper with SCENARIO_INSERT already handles @AutoGenerated columns,
		// skip redundant populateAutoGeneratedColumns() during execute().
		this.writeAutoColumns = false;
		return this;
	}

