	// 将缓存的批量对象，按旧模式写入到batches中。
	@SuppressWarnings({ "rawtypes", "unchecked" })
	private void mergeDifferentBatchMode() {
		if (batches.isEmpty() || populatedBatch.isEmpty()) {
			return;
		}
		Mapper mapper = batchMapper;
		for (Object obj : populatedBatch) {
			Map<Path<?>, Object> values = mapper.createMap(entity, obj);
			for (Map.Entry<Path<?>, Object> entry : values.entrySet()) {
				set((Path) entry.getKey(), entry.getValue());
			}
			addBatch();
		}
		populatedBatch = null;
	}

	/**
	 * Bulk 写入实现：将整批对象拼装为单条 {@code INSERT INTO t (cols) VALUES (...),(...),...} 语句，一次执行。
	 * <p>
	 * 与 {@link BatchProcessor}（一条 SQL + JDBC 多组参数）不同，Bulk 是一条 SQL 内含多组 VALUES。
	 * 采用一遍扫描算法确定固定的 SQL 列序（有效列并集），随后逐组生成 values（无效单元格写 {@code DEFAULT} 关键字），
	 * 因此各组绑定变量数量可不同（{@code ?} 与 {@code DEFAULT} 混排）。
	 * <p>
	 * 三列序：实体列序（{@code entity.getColumns()}）→ SQL 列序（有效列并集）→ 绑定列序（序列化产出的 constantPaths）。
	 */
	final class BulkProcessor {

		private final SQLBindingsAlter principle;

		/** 绑定列序：整条 bulk SQL 中所有 {@code ?} 对应的列（多组累积，可变长）。 */
		private final List<Path<?>> bindingPaths;

		/** 每组绑定值，与 {@link #bindingPaths} 顺序一一对应。 */
		private final List<Object> bindingVariables;

		private PreparedStatement stmt;

		BulkProcessor(Collection<Object> beans) {
			useLiterals = false;
			RelationalPathEx<?> pathEx = RelationalPathExImpl.toRelationPathEx(entity);
			List<Path<?>> allCols = pathEx.getColumns();
			int m = allCols.size();
			ColumnMapping[] metaColumns = new ColumnMapping[m];
			for (int i = 0; i < m; i++) {
				metaColumns[i] = pathEx.getColumnMetadata(allCols.get(i));
			}
			boolean writeNullsMode = (writeNulls != null && writeNulls);

			// —— 第一遍（唯一遍历对象）：抽值 + 求有效列并集 + 缓存原始值 ——
			Object firstBean = beans.iterator().next();
			// 包装 DTO 用 extractValues（按实体列序，未映射列为 NOT_AVAILABLE）；普通 bean 用全局共享 codec。
			BeanCodec codec = (firstBean instanceof ConverterWrappedBean) ? null
					: AdvancedMapper.getBeanCodec(pathEx, firstBean);
			List<Object[]> rows = new ArrayList<>(beans.size()); //所有对象的列值数组 
			boolean[] effective = new boolean[m];//列值有效记录 
			for (Object bean : beans) {
				Object[] raw = extractRaw(codec, pathEx, bean);
				rows.add(raw);
				for (int i = 0; i < m; i++) {
					if (metaColumns[i].isNotInsert() || isKeyAutoIncrement(metaColumns[i])) {
						continue;
					}
					Object v = raw[i];
					if (v == ConverterWrappedBean.NOT_AVAILABLE) {
						continue; // DTO 未映射该列 → 不纳入有效列（缺失单元格后续补 DEFAULT）
					}
					if (writeNullsMode) {
						effective[i] = true; // 写 NULL 模式：所有可插入列都进 SQL 列序
					} else if (metaColumns[i].getGenerated() != null
							|| !AbstractMapperSupport.isUnsavedValue(metaColumns[i], v)) {
						effective[i] = true; // 有 @AutoGenerated 或值有效 → 纳入有效列
					}
				}
			}

			// —— 固定 SQL 列序（有效列并集，保持实体列序） ——
			List<Path<?>> effectColumns = new ArrayList<>();
			int[] sqlColIdx = new int[m];
			int sqlColCount = 0;
			for (int i = 0; i < m; i++) {
				if (effective[i]) {
					effectColumns.add(allCols.get(i));
					sqlColIdx[sqlColCount++] = i;
				}
			}

			// —— 第二遍：并行遍历 beans 与 rows（同顺序同索引），按 SQL 列序生成每组 values，处理 auto 值与写回 ——
			int maxLoginBatch = configuration.getMaxRecordsLogInBatch();
			List<List<Expression<?>>> valueGroups = new ArrayList<>(rows.size());
			this.bindingVariables = new ArrayList<>();
			List<SQLBindingsAlter> logBindings = new ArrayList<>();
			Iterator<Object> beanIter = beans.iterator();
			int r = 0;
			for (Object[] raw : rows) {
				Object bean = beanIter.next(); // beans 与 rows 由第一遍按同一顺序构建，天然对齐
				List<Object> groupBindValues = new ArrayList<>(sqlColCount);
				List<Expression<?>> group = buildValueGroup(raw, bean, metaColumns, sqlColIdx,
						sqlColCount, effectColumns, writeNullsMode, groupBindValues);
				this.bindingVariables.addAll(groupBindValues);
				valueGroups.add(group);
				if (r++ < maxLoginBatch) {
					logBindings.add(new SQLBindingsAlter(null, new ArrayList<>(groupBindValues), effectColumns));
				}
			}

			// —— 序列化：单条 bulk SQL + 尾部 flags ——
			SQLSerializerAlter serializer = createSerializer();
			listeners.preRender(context);
			serializer.serializeForInsertBulk(metadata, entity, effectColumns, valueGroups);
			if (!metadata.getFlags().isEmpty()) {
				serializer.serialize(Position.END, metadata.getFlags());
			}
			this.principle = new SQLBindingsAlter(serializer.toString(), serializer.getConstants(),
					serializer.getConstantPaths());
			this.bindingPaths = serializer.getConstantPaths();
			// 尾部 flags（如 on duplicate key update set gender=?, content=concat(...)）可能引入额外的绑定常量，
			// 这些常量位于序列化产出的 constants 尾部、不在各组 VALUES 中，需要补进 bindingValues 才能正确 set。
			List<?> allConstants = serializer.getConstants();
			for (int i = bindingVariables.size(); i < allConstants.size(); i++) {
				bindingVariables.add(allConstants.get(i));
			}
			// principle（含真实 SQL）必须先入 context，日志格式化取首条的 SQL；随后追加各组展示用绑定。
			context.addSQL(principle);
			for (SQLBindingsAlter lb : logBindings) {
				context.addSQL(lb);
			}
			listeners.rendered(context);
		}

		PreparedStatement prepare(boolean withKeys) throws SQLException {
			this.stmt = createBulkStatement(principle.getSQL(), withKeys);
			List<Path<?>> paths = this.bindingPaths;
			Configuration cfg = configuration.get();
			int len = bindingVariables.size();
			for (int i = 0; i < len;) {
				Path<?> path = paths.get(i);
				Object o = bindingVariables.get(i);
				try {
					cfg.set(stmt, path, ++i, o);
				} catch (SQLException e) {
					log.error(principle.getSQL() + "\nField " + (i - 1) + " path=" + path + " set error. "
							+ e.getMessage());
					throw e;
				}
			}
			return stmt;
		}

		private PreparedStatement createBulkStatement(String sql, boolean withKeys) throws SQLException {
			PreparedStatement stmt;
			if (withKeys) {
				if (entity.getPrimaryKey() != null && !configuration.has(SpecialFeature.PREFER_AUTOGENERATED_KEYS)) {
					String[] target = new String[entity.getPrimaryKey().getLocalColumns().size()];
					for (int i = 0; i < target.length; i++) {
						Path<?> path = entity.getPrimaryKey().getLocalColumns().get(i);
						String column = ColumnMetadata.getName(path);
						column = configuration.getColumnOverride(entity.getSchemaAndTable(), column);
						target[i] = column;
					}
					stmt = connection().prepareStatement(sql, target);
				} else {
					stmt = connection().prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
				}
			} else {
				stmt = connection().prepareStatement(sql);
			}
			context.addPreparedStatement(stmt);
			return stmt;
		}

		/**
		 * 按固定 SQL 列序为单条记录生成一组 value 表达式。绑定值收集到 {@code groupBindValues}，
		 * 并对该组做防御性空值兜底（{@link #applyGroupSubstitutions}）。
		 *
		 * @param raw             该记录按实体列序抽取的原始值
		 * @param bean            原始对象（用于 @AutoGenerated 回写）
		 * @param metaColumns            实体列的 ColumnMapping（按实体列序）
		 * @param sqlColIdx       SQL 列在实体列序中的下标映射
		 * @param sqlColCount     SQL 列数
		 * @param columns         固定 SQL 列序
		 * @param writeNullsMode  writeNulls==true 时无效值写 NULL，否则写 DEFAULT 关键字
		 * @param groupBindValues 出参：本组的绑定值（与 group 中的 {@code ?} 一一对应）
		 * @return 本组的 value 表达式列表
		 */
		private List<Expression<?>> buildValueGroup(Object[] raw, Object bean, ColumnMapping[] metaColumns, int[] sqlColIdx,
				int sqlColCount, List<Path<?>> columns, boolean writeNullsMode, List<Object> groupBindValues) {
			List<Expression<?>> group = new ArrayList<>(sqlColCount);
			for (int k = 0; k < sqlColCount; k++) {
				int i = sqlColIdx[k];
				buildCell(metaColumns[i], raw[i], bean, writeNullsMode, group, groupBindValues);
			}
			// 防御层：对本组绑定值中的 null/unsaved 用 defaultExpression 兜底（穿透 DEFAULT 关键字）
			if (!groupBindValues.isEmpty()) {
				applyGroupSubstitutions(group, groupBindValues, columns);
			}
			return group;
		}

		/**
		 * 为单个列生成一个 value 单元：处理 @AutoGenerated（含回写）、无效值（写 DEFAULT 关键字或 NULL）、
		 * 内联表达式、常量绑定四种情况。结果追加到 {@code group}，若为绑定值则同时追加到 {@code groupBindValues}。
		 */
		private void buildCell(ColumnMapping cm, Object rawValue, Object bean, boolean writeNullsMode,
				List<Expression<?>> group, List<Object> groupBindValues) {
			Object v = rawValue;
			// DTO 未映射的列（NOT_AVAILABLE）等同无效 → 该单元格补 DEFAULT
			boolean unsaved = (v == ConverterWrappedBean.NOT_AVAILABLE)
					|| AbstractMapperSupport.isUnsavedValue(cm, v);
			if (v == ConverterWrappedBean.NOT_AVAILABLE) {
				v = null;
			}
			// @AutoGenerated：解析并按需回写（与 AdvancedMapper 共用逻辑，回写由 writeback 内部处理表达式值）
			Object autoV = AbstractMapperSupport.resolveAutoGenerated(cm, unsaved, SCENARIO_INSERT, bean);
			if (autoV != AbstractMapperSupport.NO_AUTO_VALUE) {
				v = autoV;
				unsaved = false;
			}
			if (unsaved) {
				if (writeNullsMode) {
					group.add(Null.CONSTANT); // 写 NULL（下方 applySubstitutions 可能兜底）
					groupBindValues.add(Null.DEFAULT);
				} else {
					group.add(DDLExpressions.defaultExpr()); // 无效 → DEFAULT 关键字（内联，不占绑定）
				}
			} else if (v instanceof Expression) {
				group.add((Expression<?>) v); // 内联表达式（currentTimestamp 等），不占绑定
			} else {
				group.add(ConstantImpl.create(v)); // 绑定 ?
				groupBindValues.add(v);
			}
		}
	}

	private static Object[] extractRaw(BeanCodec codec, RelationalPathEx<?> pathEx, Object bean) {
		if (bean instanceof ConverterWrappedBean) {
			return ((ConverterWrappedBean) bean).extractValues(pathEx);
		}
		if (codec != null && pathEx.getType().isInstance(bean)) {
			return codec.values(bean);
		}
		return AdvancedMapper.getBeanCodec(pathEx, bean).values(bean);
	}

	private static boolean isKeyAutoIncrement(ColumnMapping cm) {
		return cm.isAutoIncrement();
	}

	/**
	 * 对一组绑定值应用 {@link DefaultValueHelper#applySubstitutions} 防御兜底。
	 * group 中位于 {@code DEFAULT} 关键字或内联表达式的单元格不参与（它们不在 bindValues 中）。
	 * bindValues 与 group 中"绑定列"（{@link ConstantImpl} 或 {@link Null#CONSTANT}）一一对应。
	 */
	private void applyGroupSubstitutions(List<Expression<?>> group, List<Object> bindValues, List<Path<?>> columns) {
		List<Path<?>> bindCols = new ArrayList<>(bindValues.size());
		for (int c = 0; c < group.size(); c++) {
			Expression<?> e = group.get(c);
			if (e instanceof ConstantImpl || e == Null.CONSTANT) {
				bindCols.add(columns.get(c));
			}
		}
		if (bindCols.size() != bindValues.size()) {
			return; // 对齐异常时跳过防御兜底，避免错位
		}
		Object[] arr = bindValues.toArray();
		DefaultValueHelper.applySubstitutions(entity, bindCols, arr, getEffectiveBatchNullStrategy());
		for (int i = 0; i < arr.length; i++) {
			bindValues.set(i, arr[i]);
		}
	}
	
	/**
	 * 批量写入的优化实现。针对单一对象大批量写入，在MySQL进行性能测试。发现
	 * -- JDBC驱动的Batch性能很差，远不如MyBatis直接多组values(?),(?)拼接的速度 (194,262ms VS 10,984ms)
	 * -- 改用setBatchToBulk(true)进行测试，发现queryDSL为每个对象生成SQL再分组，也不快(16,999ms vs 7538ms)。
	 * -- 用下列方法实现后， 达到(2876ms vs 7538ms)
	 */
	final class BatchProcessor {
		private final SQLBindingsAlter principle;
		
		private final List<Path<?>> columnPaths;
		
		private final List<Path<?>> bingingPaths;
		
		private final ValueExtractor valueExtractor;

		private PreparedStatement stmt;
		
		private final int maxLoginBatch = configuration.getMaxRecordsLogInBatch();
		
		private int count = 0;

		BatchProcessor(List<Path<?>> columns,List<Expression<?>> firstValues, Object firstBean) {
			useLiterals=false;
			this.columnPaths = columns;
			SQLSerializerAlter serializer = createSerializer(); 
			listeners.preRender(context);
			serializer.serializeForInsert(metadata, entity, columns, firstValues, null);
			
			//添加定制后缀。如on duplicate update set
			if (!metadata.getFlags().isEmpty()) {
				serializer.serialize(Position.END, metadata.getFlags());
	        }
			
			principle = new SQLBindingsAlter(serializer.toString(), serializer.getConstants(),
					serializer.getConstantPaths());
			this.bingingPaths = serializer.getConstantPaths();
			if (firstBean instanceof ConverterWrappedBean) {
				this.valueExtractor = ((ConverterWrappedBean) firstBean)
						.toValueExtractor((RelationalPathEx<?>) entity, bingingPaths);
			} else {
				this.valueExtractor = BeanCodecManager.getInstance()
						.getCodec(firstBean.getClass(), new ListPathBindings(bingingPaths));
			}
			context.addSQL(principle);
			listeners.rendered(context);
		}

		private List<Object[]> collectBatchValues(Iterator<Object> iter,int len) {
			List<Object[]> result = new ArrayList<>(len);
			while(iter.hasNext()) {
				Object bean = iter.next();
				if (valueExtractor.isInstance(bean)) {
					Object[] values = this.valueExtractor.values(bean);
					DefaultValueHelper.applySubstitutions(entity, bingingPaths, values, getEffectiveBatchNullStrategy());
					if (count++ < maxLoginBatch) {
						//输入到日志用与展示的批次，仅展示部分。
						context.addSQL(new SQLBindingsAlter(null, Arrays.asList(values), bingingPaths));
					}
					result.add(values);
				} else {
					throw Exceptions.illegalArgument("Object in batch must be in consistent type {}. encounter a {}",
							valueExtractor.getType(), bean.getClass());
				}				
			}
			return result;
		}
		
		public void prepareBatchStatement(boolean withKeys,List<Object[]> values) throws SQLException {
			SQLBindingsAlter first = this.principle;
			List<Object> bindings = first.getNullFriendlyBindings();
			Object[] arr = bindings.toArray();
			DefaultValueHelper.applySubstitutions(entity, bingingPaths, arr, getEffectiveBatchNullStrategy());
			bindings = java.util.Arrays.asList(arr);
			this.stmt = createStatement(first.getSQL(), withKeys);
			
			//设置第一组绑定参数
			setParameters(stmt, bindings, first.getPaths(), null);
			stmt.addBatch();
			
			//针对每组值，设置绑定值。Batch模式是一句SQL对应多组参数，因此参数必须完全匹配一致。
			Configuration cfg = configuration.get();
			for (Object[] vs:values) { 
				addBatchParams(vs, cfg);
			}
		}
	
		private void addBatchParams(Object[] values, Configuration config) throws SQLException {
			List<Path<?>> paths = this.bingingPaths;
			PreparedStatement stmt = this.stmt;
			int len = values.length;
			for (int i = 0; i < len;) {
				Path<?> path = paths.get(i);
				Object o = values[i];
				try {
					config.set(stmt, path, ++i, o);
				} catch (SQLException e) {
					log.error(principle.getSQL() + "\nField " + (i - 1) + " path=" + path + " set error. "
							+ e.getMessage());
					throw e;
				}
			}
			stmt.addBatch();
		}
	
		private PreparedStatement createStatement(String sql, boolean withKeys) throws SQLException {
			PreparedStatement stmt;
			if (withKeys) {
				if (entity.getPrimaryKey() != null && !configuration.has(SpecialFeature.PREFER_AUTOGENERATED_KEYS)) {
					String[] target = new String[entity.getPrimaryKey().getLocalColumns().size()];
					for (int i = 0; i < target.length; i++) {
						Path<?> path = entity.getPrimaryKey().getLocalColumns().get(i);
						String column = ColumnMetadata.getName(path);
						column = configuration.getColumnOverride(entity.getSchemaAndTable(), column);
						target[i] = column;
					}
					stmt = connection().prepareStatement(sql, target);
				} else {
					stmt = connection().prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
				}
			} else {
				stmt = connection().prepareStatement(sql);
			}
			context.addPreparedStatement(stmt);
			return stmt;
		}
	}
	/*
	 *  在Batch操作中，有三个PathList的概念，需要区分清楚（以下简称三列序）
	 *  <li>Full Path（实体列序，实体的所有列）: Entity的全部列。RelationalPath.getColumns()得到这个列表</li>
	 *  <li>SQL Path（SQL列序，出现在Column中）: 参与到SQL中的列，在SQL Batch中的是是这个列表</li>
	 *  <li>Constant Path（绑定列序）: 即每条数据需要传入的列,在SQLSerializer.getConstantPath()得到这个列表</li>
	 */
	private BatchProcessor createBatch(Object obj) {
		List<Path<?>> columns = new ArrayList<>();
		List<Expression<?>> values = new ArrayList<>();
		@SuppressWarnings("unchecked")
		//这个Map决定了SQL列序
		Map<Path<?>, Object> map = batchMapper.createMap(entity, obj);
		for (Map.Entry<Path<?>, Object> entry : map.entrySet()) {
			Path<?> p = entry.getKey();
			columns.add(p);
			Object value = entry.getValue();
			if (value instanceof Expression<?>) {
				values.add((Expression<?>) value);
			} else if (value != null) {
				values.add(ConstantImpl.create(value));
			} else {
				values.add(Null.CONSTANT);
			}
		}
		return new BatchProcessor(columns, values, obj);
	}
	
	public SQLInsertClauseAlter normalizeBatch(boolean flag) {
		this.normalizeBatchValues = flag;
		return this;
	}

	/**
	 * Override the batch null strategy for this specific insert clause.
	 * This takes precedence over the global {@link ConfigurationEx#getBatchNullStrategy()}.
	 * <p>
	 * <b>Special values:</b>
	 * <ul>
	 * <li>{@code null} - Use SAFE mode (traditional addBatch path, null columns omitted from SQL)</li>
	 * <li>{@link BatchNullStrategy#AUTO_DEFAULT} - Use defaultExpression for NOT NULL columns</li>
	 * <li>{@link BatchNullStrategy#AGGRESSIVE_DEFAULT} - Provide fallback values even without defaultExpression</li>
	 * <li>Custom strategy - Use {@link BatchNullStrategy#of} or {@code withXxxStrategy()} methods</li>
	 * </ul>
	 * <p>
	 * <h2>中文</h2>
	 * 为当前插入语句覆盖批量null值处理策略，优先于全局配置。
	 * <p>
	 * <b>特殊值：</b>
	 * <ul>
	 * <li>{@code null} - 使用安全模式（传统 addBatch 路径，null 列从 SQL 中省略）</li>
	 * <li>{@link BatchNullStrategy#AUTO_DEFAULT} - 对 NOT NULL 列使用 defaultExpression</li>
	 * <li>{@link BatchNullStrategy#AGGRESSIVE_DEFAULT} - 即使没有 defaultExpression 也提供兜底值</li>
	 * <li>自定义策略 - 使用 {@link BatchNullStrategy#of} 或 {@code withXxxStrategy()} 方法</li>
	 * </ul>
	 *
	 * @param strategy the strategy to use for this batch insert, or null for SAFE mode
	 * @return this SQLInsertClauseAlter
	 * @see com.github.xuse.querydsl.config.BatchNullStrategy
	 */
	public SQLInsertClauseAlter batchNullStrategy(com.github.xuse.querydsl.config.BatchNullStrategy strategy) {
		this.overrideBatchNullStrategy = strategy;
		return this;
	}

	private com.github.xuse.querydsl.config.BatchNullStrategy getEffectiveBatchNullStrategy() {
		if (overrideBatchNullStrategy == NOT_SET) {
			return configuration.getBatchNullStrategy();
		}
		return overrideBatchNullStrategy;
	}
